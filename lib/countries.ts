export type Country = { code: string; name: string };

/** The country's name in the app's language. */
export function countryName(code: string) {
  const row = COUNTRIES.find(([c]) => c === code);
  if (!row) return code;
  return getLanguage() === 'en' ? row[1] : row[2];
}

/** All countries, named in the app's language and sorted by that name. */
export function countryList(): Country[] {
  const en = getLanguage() === 'en';
  return COUNTRIES.map(([code, nameEn, nameId]) => ({ code, name: en ? nameEn : nameId })).sort(
    (a, b) => a.name.localeCompare(b.name)
  );
}

/** The flag emoji for a two-letter country code. */
export function countryFlag(code: string) {
  return String.fromCodePoint(...[...code.toUpperCase()].map((c) => 0x1f1a5 + c.charCodeAt(0)));
}
